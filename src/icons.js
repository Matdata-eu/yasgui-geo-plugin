/** Names of the inlined icons. */
export const ICON_NAMES = Object.freeze(Object.keys(ICONS));

/**
 * SVG markup of a Lucide icon.
 * @param {string} name - one of ICON_NAMES
 * @param {{ size?: number, strokeWidth?: number }} [opts]
 * @returns {string}
 */
export const iconMarkup = (name, { size = 16, strokeWidth = 1.75 } = {}) => {
  const body = ICONS[name];
  if (!body) throw new Error(`yasgui-geo-plugin: unknown icon "${name}"`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" class="yasgui-geo-icon" aria-hidden="true" focusable="false">${body}</svg>`;
};

/**
 * A Lucide icon as an SVG element. Decorative: the control carrying it gets
 * the accessible name.
 * @param {string} name - one of ICON_NAMES
 * @param {{ size?: number, strokeWidth?: number, doc?: Document }} [opts]
 * @returns {SVGSVGElement}
 */
export const icon = (name, { doc = document, ...opts } = {}) => {
  const template = doc.createElement('template');
  template.innerHTML = iconMarkup(name, opts);
  return template.content.firstElementChild;
};

/**
 * Replace the content of a map-control button (a Leaflet `.leaflet-bar a`)
 * with an icon, centred by the `yasgui-geo-icon-btn` class.
 * @param {HTMLElement} el
 * @param {string} name - one of ICON_NAMES
 * @returns {HTMLElement} el
 */
export const setIcon = (el, name) => {
  el.replaceChildren(icon(name, { doc: el.ownerDocument }));
  el.classList.add('yasgui-geo-icon-btn');
  return el;
};
